#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum CompatRulePolicy {
    Global,
    ShowUi,
    Ascii,
    HideUi,
    DisableTopmost,
    DisableInlinePreedit,
    DisableEnhancedPosition,
    FocusStrict,
    FocusWindow,
}

impl CompatRulePolicy {
    pub(crate) const ALL: [Self; 9] = [
        Self::Global,
        Self::ShowUi,
        Self::Ascii,
        Self::HideUi,
        Self::DisableTopmost,
        Self::DisableInlinePreedit,
        Self::DisableEnhancedPosition,
        Self::FocusStrict,
        Self::FocusWindow,
    ];

    pub(crate) fn label(self) -> &'static str {
        match self {
            Self::ShowUi => "显示候选栏",
            Self::Global => "使用全局策略",
            Self::Ascii => "强制英文模式",
            Self::HideUi => "隐藏候选界面",
            Self::DisableTopmost => "禁用置顶",
            Self::DisableInlinePreedit => "禁用内嵌预编辑",
            Self::DisableEnhancedPosition => "关闭增强定位",
            Self::FocusStrict => "焦点严格定位",
            Self::FocusWindow => "窗口兜底定位",
        }
    }

    pub(crate) fn config_name(self) -> &'static str {
        match self {
            Self::ShowUi => "show_ui",
            Self::Global => "global",
            Self::Ascii => "ascii",
            Self::HideUi => "hide_ui",
            Self::DisableTopmost => "topmost_off",
            Self::DisableInlinePreedit => "inline_off",
            Self::DisableEnhancedPosition => "position_off",
            Self::FocusStrict => "focus_strict",
            Self::FocusWindow => "focus_window",
        }
    }

    pub(crate) fn from_config_name(value: &str) -> Self {
        match value.trim().to_ascii_lowercase().as_str() {
            "show_ui" | "show-ui" | "show" | "overlay" | "candidate_ui" => Self::ShowUi,
            "ascii" | "ascii_mode" => Self::Ascii,
            "hide" | "hide_ui" => Self::HideUi,
            "topmost_off" | "candidate_topmost_off" => Self::DisableTopmost,
            "inline_off" | "inline_preedit_off" => Self::DisableInlinePreedit,
            "position_off" | "enhanced_position_off" => Self::DisableEnhancedPosition,
            "focus_strict" | "strict_focus" | "strict" => Self::FocusStrict,
            "focus_window" | "window_focus" | "window" => Self::FocusWindow,
            _ => Self::Global,
        }
    }
}

