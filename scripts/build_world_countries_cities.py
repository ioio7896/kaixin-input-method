def parse_rows() -> list[tuple[str, list[str]]]:
    rows: list[tuple[str, list[str]]] = []
    for raw in COUNTRY_ROWS.splitlines():
        raw = raw.strip()
        if not raw:
            continue
        fields = raw.split("|")
        if len(fields) != 6 or any(not field for field in fields):
            raise ValueError(f"invalid country row: {raw}")
        country, *cities = fields
        rows.append((country, cities))
    if len(rows) != 195:
        raise ValueError(f"expected 195 countries, got {len(rows)}")
    return rows


def build(output: Path) -> tuple[int, int]:
    rows = parse_rows()
    output.parent.mkdir(parents=True, exist_ok=True)
    entries: list[tuple[str, str, int]] = []
    seen: set[str] = set()
    for country, cities in rows:
        for phrase, weight in [(country, 180000), *[(city, 65000) for city in cities]]:
            if phrase in seen:
                continue
            seen.add(phrase)
            code = " ".join(lazy_pinyin(phrase, style=Style.NORMAL))
            entries.append((phrase, code, weight))
    with output.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("# 开心输入法原生词库：世界国家及主要城市\n")
        stream.write("# 195 个国家（193 个联合国会员国＋巴勒斯坦、梵蒂冈）及每国 5 个代表性城市。\n")
        stream.write("# 城市为常用中文名称；格式：词语<TAB>全拼<TAB>权重。\n")
        for phrase, code, weight in entries:
            stream.write(f"{phrase}\t{code}\t{weight}\n")
    return len(rows), len(entries)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1]
        / "lexicon"
        / "base"
        / "world_countries_major_cities.txt",
    )
    args = parser.parse_args()
    countries, entries = build(args.output)
    print(f"countries={countries} entries={entries} output={args.output}")


if __name__ == "__main__":
    main()
