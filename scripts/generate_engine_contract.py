"""Render the Rust/C++ constants used at the engine transport boundary."""

import json
from pathlib import Path


def render_engine_contract(root: Path) -> dict[str, str]:
    contract = json.loads((root / "shared/engine_contract.json").read_text(encoding="utf-8"))
    limits = contract["limits"]
    if not (0 < limits["page_size"] <= limits["initial_candidates"] <= limits["full_candidates"]):
        raise ValueError("Candidate limits must be positive and ordered")
    if limits["full_candidates"] < 1024:
        raise ValueError("Full candidate capacity must cover the supported single-character pool")
    modes = contract["mode_flags"]
    values = list(modes.values())
    if len(values) != len(set(values)) or any(v <= 0 or v & (v - 1) for v in values):
        raise ValueError("Engine modes must use distinct single bits")
    rust = (
        "// Generated by scripts/generate_shared_contracts.py; edit shared/engine_contract.json.\n"
    )
    cpp = "#pragma once\n// Generated by scripts/generate_shared_contracts.py.\n#include <cstddef>\n#include <cstdint>\nnamespace srf_engine_contract {\n"
    for name, value in {
        "TSF_PAGE_SIZE": limits["page_size"],
        "TSF_MAX_CANDIDATES": limits["initial_candidates"],
        "LOOKUP_FULL_MAX_CANDIDATES": limits["full_candidates"],
    }.items():
        rust += f"pub const {name}: usize = {value};\n"
        cpp += f"inline constexpr std::size_t {name} = {value};\n"
    for group in (modes, contract["learn_flags"], contract["candidate_frame"]):
        for name, value in group.items():
            rust += f"pub const {name}: u32 = {value};\n"
            cpp += f"inline constexpr std::uint32_t {name} = {value};\n"
    cpp += "}  // namespace srf_engine_contract\n"
    return {
        "crates/kaixin-common/src/engine_contract.rs": rust,
        "tsf-tip/include/engine_contract.generated.h": cpp,
    }
